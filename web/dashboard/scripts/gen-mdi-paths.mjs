#!/usr/bin/env node
// Regenerates src/plugins/mdiPaths.ts from actual icon usage.
//
// We ship SVG paths (@mdi/js) instead of the @mdi/font webfont: the font
// bundles all 7000+ glyphs (~400KB woff2 + ~90KB gzip CSS) while the app
// uses ~90. Templates keep writing plain `mdi-*` names — the custom
// iconset in plugins/vuetify.ts resolves names through this map, so
// adding an icon = use it in a template, then run `yarn gen:icons`.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'src')
const outFile = join(srcDir, 'plugins', 'mdiPaths.ts')

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else if (/\.(vue|ts)$/.test(name) && !p.endsWith('mdiPaths.ts')) yield p
  }
}

const used = new Set()
for (const file of walk(srcDir)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/\bmdi-[a-z0-9]+(?:-[a-z0-9]+)*\b/g)) {
    used.add(m[0])
  }
}

const toExport = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

const mdi = await import('@mdi/js')
const names = [...used].sort()
const missing = names.filter((n) => !(toExport(n) in mdi))
if (missing.length > 0) {
  console.error(`gen-mdi-paths: unknown icon name(s): ${missing.join(', ')}`)
  process.exit(1)
}

const imports = names.map(toExport).join(',\n  ')
const entries = names.map((n) => `  '${n}': ${toExport(n)},`).join('\n')
writeFileSync(outFile, `// AUTO-GENERATED by scripts/gen-mdi-paths.mjs — do not edit by hand.
// Regenerate with \`yarn gen:icons\` after adding a new mdi-* icon name.
import {
  ${imports},
} from '@mdi/js'

export const MDI_PATHS: Record<string, string> = {
${entries}
}
`)
console.log(`gen-mdi-paths: wrote ${names.length} icons to src/plugins/mdiPaths.ts`)
